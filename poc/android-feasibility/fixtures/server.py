"""Fixture web server for the Android feasibility app (PoC A1-A3).

Serves harmless test pages and download cases on localhost; the emulator
reaches it through `adb reverse tcp:8765 tcp:8765`, which makes the origin
http://localhost:8765 a secure context (needed for service workers).

Usage: python3 -I server.py [port]
"""

import hashlib
import http.server
import json
import pathlib
import sys
import urllib.parse

WEB_ROOT = pathlib.Path(__file__).resolve().parent / "web"
PLAIN = bytes((i * 7) % 256 for i in range(200_000))
DISPOSITION = b"%PDF-1.4\n% rift download fixture\n" + bytes(1000)
PRIVATE = b"cookie-gated content " * 1000
POSTED = b"generated by POST " * 500
SESSION_COOKIE = "rift_session=s3cr3t"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


EXPECTED = {
    "plain_get": sha256(PLAIN),
    "content_disposition": sha256(DISPOSITION),
    "redirect": sha256(PLAIN),
    "cookie_gated": sha256(PRIVATE),
    "post_form": sha256(POSTED),
}


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(WEB_ROOT), **kwargs)

    def send_bytes(self, body: bytes, content_type: str, extra=()):
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for key, value in extra:
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):  # noqa: N802 (http.server naming)
        url = urllib.parse.urlparse(self.path)
        if url.path == "/expected.json":
            return self.send_bytes(json.dumps(EXPECTED).encode(), "application/json")
        if url.path == "/files/plain.bin":
            return self.send_bytes(PLAIN, "application/octet-stream")
        if url.path == "/files/disposition":
            # Hostile filename: traversal plus a right-to-left override character.
            name = '../../evil‮gpj.pdf'
            return self.send_bytes(
                DISPOSITION,
                "application/pdf",
                [("Content-Disposition", f'attachment; filename="{name}"'.encode("utf-8").decode("latin-1"))],
            )
        if url.path == "/redirect":
            self.send_response(302)
            self.send_header("Location", "/files/plain.bin")
            self.end_headers()
            return None
        if url.path == "/login":
            target = urllib.parse.parse_qs(url.query).get("next", ["/"])[0]
            self.send_response(302)
            self.send_header("Set-Cookie", f"{SESSION_COOKIE}; Path=/; HttpOnly")
            self.send_header("Location", target)
            self.end_headers()
            return None
        if url.path == "/files/private.bin":
            if SESSION_COOKIE not in (self.headers.get("Cookie") or ""):
                self.send_response(403)
                self.end_headers()
                return None
            return self.send_bytes(PRIVATE, "application/octet-stream", [("Content-Disposition", "attachment")])
        if url.path == "/files/post-result":
            # A GET re-fetch of a POST-only download must not silently succeed.
            self.send_response(405)
            self.end_headers()
            return None
        if url.path == "/a2-seed.html":
            body = (WEB_ROOT / "a2-seed.html").read_bytes()
            return self.send_bytes(
                body, "text/html", [("Set-Cookie", "rift_server_cookie=persisted; Max-Age=86400; Path=/")]
            )
        if url.path == "/cacheable.js":
            return self.send_bytes(b"/* cacheable */", "text/javascript", [("Cache-Control", "max-age=86400")])
        return super().do_GET()

    def do_POST(self):  # noqa: N802
        if urllib.parse.urlparse(self.path).path == "/files/post-result":
            length = int(self.headers.get("Content-Length") or 0)
            self.rfile.read(min(length, 4096))
            return self.send_bytes(POSTED, "application/octet-stream", [("Content-Disposition", "attachment")])
        self.send_response(404)
        self.end_headers()
        return None

    def log_message(self, fmt, *args):
        sys.stderr.write("fixture: " + (fmt % args) + "\n")


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8765
    http.server.ThreadingHTTPServer(("127.0.0.1", port), Handler).serve_forever()
